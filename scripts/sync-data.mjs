// Copies the compiled dataset, trained models and the engine/sequencer from the data workspace into the app.
// Usage: npm run data -- /path/to/zero-proof-lab
import { cpSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const src = process.argv[2] || '../zero-proof-lab';
for (const f of ['drinks', 'ingredients', 'taxonomy']) writeFileSync(join('public/data', f + '.json'), JSON.stringify(JSON.parse(readFileSync(join(src, 'data', f + '.json'), 'utf8'))));
for (const f of ['model', 'order']) cpSync(join(src, 'model', f + '.json'), join('public/data', f + '.json'));

// The engine and sequencer are UMD (browser + Node). Unwrap them into ES modules for Vite.
function toEsm(file, out, header) {
  const text = readFileSync(join(src, 'src', file), 'utf8');
  const start = text.indexOf('function () {', text.indexOf('typeof self'));
  const body = text.slice(text.indexOf('\n', start) + 1);
  const retAt = body.lastIndexOf('\n  return {');
  const retLine = body.slice(retAt + 1, body.indexOf('}', retAt) + 1);
  const names = retLine.replace(/return\s*\{|\}|;/g, '').split(',').map(s => s.trim().split(':')[0].trim()).filter(Boolean);
  const inner = body.slice(0, retAt).split('\n').map(l => l.replace(/^  /, '')).join('\n');
  writeFileSync(join('src/lib', out), `${header}\n/* eslint-disable */\n${inner}\nexport { ${names.join(', ')} };\n`);
}
toEsm('engine.js', 'engine.js', '// ESM build of zero-proof-lab/src/engine.js (generated by scripts/sync-data.mjs, do not edit).');
toEsm('sequencer.js', 'sequencer.js', '// ESM build of zero-proof-lab/src/sequencer.js (generated by scripts/sync-data.mjs, do not edit).');
console.log('synced from', src);
